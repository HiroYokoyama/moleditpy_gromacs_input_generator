import pytest
from helpers import assemble, ethanol, example_mdff_path, example_system, ion, water

from gromacs_input_generator import ff_tables, mdff, topology


def test_builtin_fallback_counts_copies_and_marks_todo():
    model = assemble([ethanol(), ethanol((5, 0, 0)), water((10, 0, 0)), water((14, 0, 0)),
                      ion("Na", (20, 0, 0)), ion("Cl", (24, 0, 0))], [0] * 24 + [1, -1])
    topo = topology.build_topology(model)
    assert topo.molecules() == [("MOL", 2), ("SOL", 2), ("NA", 1), ("CL", 1)]
    assert topo.moltypes["MOL"].is_todo
    assert topo.has_todo
    assert any("Force Field Builder" in w for w in topo.warnings)
    top = topology.write_top(topo)
    assert '#include "MOL.itp"' in top and "TODO" in top
    itp = topology.write_itp(topo.moltypes["MOL"])
    assert "TODO_C" in itp and "Force Field Builder" in itp
    assert "    1     2" in itp  # connectivity without parameters


def test_non_consecutive_copies_get_separate_molecule_rows():
    model = assemble([water(), ion("Na", (5, 0, 0)), water((10, 0, 0))])
    topo = topology.build_topology(model)
    assert topo.molecules() == [("SOL", 1), ("NA", 1), ("SOL", 1)]


@pytest.mark.parametrize("model_name", ["TIP3P", "SPC/E"])
def test_builtin_water_and_ions(model_name):
    model = assemble([water(order="HOH"), ion("K", (5, 0, 0)), ion("Br", (9, 0, 0))])
    topo = topology.build_topology(model, water_model=model_name)
    w = ff_tables.WATER_MODELS[model_name]
    sol = topo.moltypes["SOL"]
    assert [a["name"] for a in sol.atoms] == ["OW", "HW1", "HW2"]
    assert sol.charge == pytest.approx(0.0)
    assert sol.settles == (0, w["doh"], pytest.approx(w["dhh"]))
    # H O H in the host becomes O H H in topology order
    assert topo.blocks[0].atoms == [1, 0, 2]
    assert topo.reordered
    itp = topology.write_itp(sol)
    assert "[ settles ]" in itp and "#ifndef FLEXIBLE" in itp and "[ exclusions ]" in itp
    assert topo.moltypes["K"].charge == 1.0 and topo.moltypes["BR"].charge == -1.0
    assert topo.atomtypes[ff_tables.ion_parameters("K", model_name)["type"]]["sigma"] > 0


def test_dhh_matches_geometry():
    tip3p = ff_tables.WATER_MODELS["TIP3P"]
