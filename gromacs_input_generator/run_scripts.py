"""run.sh / run.bat chaining gmx grompp and gmx mdrun over the enabled stages."""

from __future__ import annotations

_PREVIOUS = {"nvt": "em", "npt": "nvt", "md": "npt"}


def stage_commands(stages: list[str], conf: str, top: str, index: str = "",
                   posres: bool = False) -> list[tuple[str, str]]:
    """(stage, grompp args) for each stage; mdrun is always ``-deffnm stage``."""
    commands = []
    previous = None
    for stage in stages:
        coords = f"{previous}.gro" if previous else conf
        args = f"grompp -f {stage}.mdp -c {coords} -p {top} -o {stage}.tpr"
        if posres and stage in ("nvt", "npt"):
            args += f" -r {coords}"
        if previous and previous != "em":
            args += f" -t {previous}.cpt"
        if index:
            args += f" -n {index}"
        commands.append((stage, args))
        previous = stage
    return commands


def run_sh(stages, conf, top, index="", posres=False) -> str:
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by the MoleditPy GROMACS Input Generator.",
        "# Override the binary with GMX=gmx_mpi ./run.sh; extra mdrun flags with MDRUN_FLAGS.",
        "set -euo pipefail",
        'cd "$(dirname "$0")"',
        'GMX="${GMX:-gmx}"',
        'MDRUN_FLAGS="${MDRUN_FLAGS:-}"',
        "",
    ]
    for stage, args in stage_commands(stages, conf, top, index, posres):
        lines += [
            f'echo "=== {stage} ==="',
            f'"$GMX" {args} -maxwarn 0',
            f'"$GMX" mdrun -deffnm {stage} $MDRUN_FLAGS',
            "",
        ]
    lines.append('echo "All stages finished."')
    return "\n".join(lines) + "\n"


def run_bat(stages, conf, top, index="", posres=False) -> str:
    lines = [
        "@echo off",
        "rem Generated by the MoleditPy GROMACS Input Generator.",
        "rem Set GMX to override the binary (e.g. set GMX=gmx_mpi), MDRUN_FLAGS for mdrun.",
        "setlocal",
        'cd /d "%~dp0"',
        'if "%GMX%"=="" set GMX=gmx',
        "",
    ]
    for stage, args in stage_commands(stages, conf, top, index, posres):
        lines += [
            f"echo === {stage} ===",
            f"%GMX% {args} -maxwarn 0 || goto :error",
            f"%GMX% mdrun -deffnm {stage} %MDRUN_FLAGS% || goto :error",
            "",
        ]
    lines += ["echo All stages finished.", "exit /b 0", "", ":error",
              "echo A GROMACS step failed; see the messages above.", "exit /b 1"]
    return "\r\n".join(lines) + "\r\n"
