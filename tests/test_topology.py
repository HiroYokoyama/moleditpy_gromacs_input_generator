def test_pairs_14():
    # butane-like chain 0-1-2-3 plus a branch 1-4
    pairs = topology.pairs_14(5, [(0, 1), (1, 2), (2, 3), (1, 4)])
    assert pairs == [(0, 3), (3, 4)]
    # a 4-ring has no 1-4 pairs (every pair is 1-2 or 1-3)
    assert topology.pairs_14(4, [(0, 1), (1, 2), (2, 3), (3, 0)]) == []


def test_atomtype_clash_is_renamed():
    atomtypes, warnings = {}, []
    assert topology._add_atomtype(atomtypes, "C", "C", 12.0, 0.3, 0.4, warnings) == "C"
    assert topology._add_atomtype(atomtypes, "C", "C", 12.0, 0.3, 0.4, warnings) == "C"
    assert topology._add_atomtype(atomtypes, "C", "C", 12.0, 0.35, 0.4, warnings) == "C_2"
    assert topology._add_atomtype(atomtypes, "C", "C", 12.0, 0.35, 0.4, warnings) == "C_2"
    assert len(warnings) == 1


def test_combination_rule_1_writes_c6_c12():
    model = assemble([ion("Na", (0, 0, 0))], [1])
    topo = topology.build_topology(model)
    topo.combination_rule = 1
    top = topology.write_top(topo)
    params = ff_tables.ion_parameters("Na", "TIP3P")
    c6 = 4 * params["epsilon"] * params["sigma"] ** 6
    line = next(line for line in top.splitlines() if line.startswith("NA_tip3p"))
    assert float(line.split()[5]) == pytest.approx(c6, rel=1e-6)
    assert "c6" in top


