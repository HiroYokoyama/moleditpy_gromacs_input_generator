def test_residue_names_name_the_skeleton():
    from gromacs_input_generator.system_model import build_system

    model = build_system(["C", "O"], [[0, 0, 0], [1.2, 0, 0]], [(0, 1)], resnames=["LIG", "LIG"],
                         resnums=[5, 5], names=["C1", "O1"])
    topo = topology.build_topology(model)
    mt = topo.moltypes["LIG"]
    assert [a["name"] for a in mt.atoms] == ["C1", "O1"]
    assert mt.atoms[0]["resnr"] == 1 and mt.atoms[0]["resname"] == "LIG"
